#!/usr/bin/env python3
"""Run prepared LoCoBench memory eval cases with Code Agent CLI."""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from locobench.memory_eval.runner import run_batch


def main() -> None:
    parser = argparse.ArgumentParser(description="Run LoCoBench memory eval cases")
    parser.add_argument("--prepared", required=True, type=Path)
    parser.add_argument("--agent-bin", default="codeagentcli")
    parser.add_argument(
        "--memory-mode",
        choices=[
            "on",
            "off",
            "memory_on",
            "memory_off",
            "native",
            "native_memory_on",
            "openviking",
            "openviking_on",
            "bare",
        ],
        required=True,
    )
    parser.add_argument("--plugin-dir", type=Path, default=None, help="CodeAgent OpenViking plugin directory for OpenViking modes")
    parser.add_argument("--openviking-url", default="http://127.0.0.1:1933")
    parser.add_argument("--openviking-account", default="memory-eval")
    parser.add_argument("--openviking-user-prefix", default=None)
    parser.add_argument("--openviking-peer-prefix", default=None)
    parser.add_argument("--run-namespace", default=None, help="Optional remote-memory run namespace; generated by default")
    parser.add_argument("--openviking-debug", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--timeout-sec", type=int, default=1800)
    parser.add_argument(
        "--memory-settle-sec",
        type=float,
        default=10.0,
        help="Seconds to wait between sessions for native/OpenViking memory backends; set 0 to disable",
    )
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--scenario-id", default=None)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--test-executor", choices=["host", "docker"], default=None, help="Executor for final post-run tests; formal batch should use docker when available")
    parser.add_argument("--docker-image", default=None, help="Docker image for post-run tests when --test-executor docker")
    parser.add_argument("--docker-network", default="none", help="Docker network mode for post-run tests")
    args = parser.parse_args()

    summary = run_batch(
        prepared_dir=args.prepared,
        agent_bin=args.agent_bin,
        memory_mode=args.memory_mode,
        output_dir=args.output,
        timeout_sec=args.timeout_sec,
        limit=args.limit,
        scenario_id=args.scenario_id,
        resume=args.resume,
        progress=lambda message: print(message, flush=True),
        plugin_dir=args.plugin_dir,
        openviking_url=args.openviking_url,
        openviking_account=args.openviking_account,
        openviking_user_prefix=args.openviking_user_prefix,
        openviking_peer_prefix=args.openviking_peer_prefix,
        openviking_debug=args.openviking_debug,
        test_executor=args.test_executor,
        docker_image=args.docker_image,
        docker_network=args.docker_network,
        memory_settle_sec=args.memory_settle_sec,
        run_namespace=args.run_namespace,
    )
    print(
        f"Run complete: {summary['completed_cases']}/{summary['case_count']} completed "
        f"for memory_mode={summary['memory_mode']}"
    )
    if summary.get("failed_cases", 0):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
