class MetricCalculatorFactory:
    """
    Factory that instantiates and wires metric calculators.
    """

    DEFAULT_CALCULATORS = (
        ColorPaletteCalculator,
        LocationHotspotCalculator,
        MoodScoreCalculator,
    )

    @classmethod
    def create_default(cls) -> List[BaseMetricCalculator]:
        return [calc() for calc in cls.DEFAULT_CALCULATORS]


# =============================================================================
# Singleton AnalyticsAggregator
# =============================================================================
class _Singleton(type):
    """
    Basic singleton meta to ensure a single aggregator per process.
    """

    _instances: Dict[type, "AnalyticsAggregator"] = {}
    _lock = threading.Lock()

    def __call__(cls, *args, **kwargs):  # noqa: D401
        with cls._lock:
            if cls not in cls._instances:
                cls._instances[cls] = super().__call__(*args, **kwargs)
        return cls._instances[cls]


class AnalyticsAggregator(metaclass=_Singleton):
    """
    Thread-safe, pluggable analytics aggregator (Observer + Factory + Singleton).

    Usage
    -----
    aggregator = AnalyticsAggregator()
    aggregator.record_event(...)
    aggregator.register_observer(view_model)
    """

    # Public configuration knobs
    FLUSH_INTERVAL_SEC = 5.0
    PERSIST_PATH = Path(os.getenv("PRISM_LOCAL_DATA", Path.home() / ".prism_pocket")) / "analytics_snapshot.json"

    # ---------------------------------------------------------------------
    def __init__(self) -> None:
        self._event_queue: "Queue[AnalyticsEvent]" = Queue()
        self._observers: List[MetricObserver] = []
        self._calculators = {
            calc.name: calc for calc in MetricCalculatorFactory.create_default()
        }
        self._metrics_lock = threading.Lock()
        self._metrics_cache: Dict[str, Any] = {}
        self._stop_event = threading.Event()

        self._hydrate_state()
        self._worker_thread = threading.Thread(
            target=self._worker_loop, name="AnalyticsProcessor", daemon=True
        )
        self._worker_thread.start()

        logger.info("AnalyticsAggregator initialised with calculators: %s", list(self._calculators))

    # ---------------------------------------------------------------------
    # Public API
    # ---------------------------------------------------------------------
    def record_event(self, event: AnalyticsEvent | Dict[str, Any]) -> None:
        """
        Accepts either AnalyticsEvent or raw dict for convenience.
        """
        if isinstance(event, dict):
            try:
                event = AnalyticsEvent(**event)
            except TypeError as exc:
                logger.warning("Invalid event skipped (%s) – %s", event, exc)
                return

        self._event_queue.put(event)

    def register_observer(self, obs: MetricObserver) -> None:
        if obs not in self._observers:
            self._observers.append(obs)
            # Immediately push current metrics for first paint
            obs.on_metric_update(self._metrics_cache)

    def unregister_observer(self, obs: MetricObserver) -> None:
        try:
            self._observers.remove(obs)
        except ValueError:
            pass

    def shutdown(self, block: bool = False) -> None:
        """
        Gracefully shut down worker thread and persist state.
        """
        logger.info("Shutting down AnalyticsAggregator")
        self._stop_event.set()
        if block:
            self._worker_thread.join(timeout=5.0)

    # ---------------------------------------------------------------------
    # Internal helpers
    # ---------------------------------------------------------------------
    def _worker_loop(self) -> None:
        """
        Consumes events, updates calculators, flushes metrics periodically.
        """
        logger.debug("Analytics worker thread running")
        last_flush = time.monotonic()

        while not self._stop_event.is_set():
            try:
                event = self._event_queue.get(timeout=0.5)
                for calculator in self._calculators.values():
                    calculator.update(event)
            except Empty:
                pass  # nothing yet

            now = time.monotonic()
            if now - last_flush >= self.FLUSH_INTERVAL_SEC:
                self._flush_metrics()
                last_flush = now

        # Final flush when exiting
        self._flush_metrics()
        self._persist_state()

    def _flush_metrics(self) -> None:
        """
        Build snapshot and broadcast to observers.
        """
        snapshot = {
            name: calc.snapshot() for name, calc in self._calculators.items()
        }

        with self._metrics_lock:
            self._metrics_cache = snapshot

        logger.debug("Metrics flushed: %s", snapshot)

        # Fan-out to observers (fire-and-forget)
        for observer in list(self._observers):
            try:
                observer.on_metric_update(snapshot)
            except Exception:  # noqa: BLE001
                logger.exception("Observer error; unregistered.")
                self.unregister_observer(observer)

    # ---------------------------------------------------------------------
    # Persistence
    # ---------------------------------------------------------------------
    def _persist_state(self) -> None:
        """
        Serialise calculator state to local JSON for offline continuation.
        """
        try:
            self.PERSIST_PATH.parent.mkdir(parents=True, exist_ok=True)
            with self.PERSIST_PATH.open("w", encoding="utf-8") as fh:
                json.dump(self._metrics_cache, fh, indent=2)
            logger.info("Analytics snapshot persisted to %s", self.PERSIST_PATH)
        except OSError:
            logger.exception("Failed to persist analytics snapshot")

    def _hydrate_state(self) -> None:
        """
        Load last known snapshot, adjusting calculators so metrics resume.
        """
        if not self.PERSIST_PATH.exists():
            return

        try:
            with self.PERSIST_PATH.open("r", encoding="utf-8") as fh:
                previous = json.load(fh)
        except (OSError, json.JSONDecodeError):
            logger.warning("Analytics snapshot unreadable, starting fresh")
            return

        # Try delegating the snapshot back into calculators if compatible
        for name, state in previous.items():
            calc = self._calculators.get(name)
            if not calc:
                continue

            if isinstance(calc, ColorPaletteCalculator):
                calc._counter = Counter(state)  # type: ignore[attr-defined]
            elif isinstance(calc, LocationHotspotCalculator):
                calc._counter = Counter(state)  # type: ignore[attr-defined]
            elif isinstance(calc, MoodScoreCalculator):
                calc._total = state.get("average", 0.0) * state.get("samples", 0)  # type: ignore[attr-defined]
                calc._count = state.get("samples", 0)  # type: ignore[attr-defined]

        # Immediately flush so observers have something to render
        self._flush_metrics()


