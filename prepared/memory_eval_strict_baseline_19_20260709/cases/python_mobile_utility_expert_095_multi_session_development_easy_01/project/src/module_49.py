class AnalyticsEvent(MutableMapping[str, Any]):
    """
    Simple dictionary-like wrapper that enforces mandatory keys.

    Parameters
    ----------
    event_type:
        Semantic identifier for downstream calculators
    payload:
        Arbitrary JSON-serialisable dict
    ts:
        Timestamp (UTC ISO-8601).  Autogenerated if omitted.
    """

    REQUIRED_KEYS = {"event_type", "payload", "ts"}

    def __init__(
        self,
        event_type: str,
        payload: Dict[str, Any],
        ts: str | None = None,
    ) -> None:
        self._store: Dict[str, Any] = {
            "event_type": event_type,
            "payload": payload,
            "ts": ts or datetime.utcnow().isoformat(),
        }

    # MutableMapping protocol -------------------------------------------------
    def __getitem__(self, key: str) -> Any:
        return self._store[key]

    def __setitem__(self, key: str, value: Any) -> None:
        self._store[key] = value

    def __delitem__(self, key: str) -> None:  # pragma: no cover
        raise TypeError("AnalyticsEvent is not deletable")

    def __iter__(self):
        return iter(self._store)

    def __len__(self) -> int:
        return len(self._store)

    # Helper methods ----------------------------------------------------------
    def to_dict(self) -> Dict[str, Any]:
        return dict(self._store)


# =============================================================================
# Observer Pattern
# =============================================================================
class MetricObserver(Protocol):
    """
    Client components implement this interface to receive metric snapshots.
    """

    def on_metric_update(self, metrics: Dict[str, Any]) -> None: ...


# =============================================================================
# Metric Calculator Framework
# =============================================================================
class BaseMetricCalculator(ABC):
    """
    Abstract strategy computing metric snapshots.
    """

    @abstractmethod
    def update(self, event: AnalyticsEvent) -> None:
        """
        Consume an event and adjust internal state.

        Calculators MUST be thread-safe (will be used from a single worker
        thread, but seriousness never hurts).
        """

    @abstractmethod
    def snapshot(self) -> Dict[str, Any]:
        """
        Return a JSON-serialisable object representing the current metric.
        """

    @property
    @abstractmethod
    def name(self) -> str: ...


# -----------------------------------------------------------------------------


class ColorPaletteCalculator(BaseMetricCalculator):
    """
    Tracks frequency of color palettes used across cards.
    """

    def __init__(self) -> None:
        self._counter: Counter[str] = Counter()

    @property
    def name(self) -> str:
        return "palette"

    def update(self, event: AnalyticsEvent) -> None:
        if event["event_type"] != "palette":
            return

        palette_id: str | None = event["payload"].get("palette_id")
        if palette_id:
            self._counter[palette_id] += 1

    def snapshot(self) -> Dict[str, Any]:
        """
        Return top 5 palettes and counts
        """
        most_common = self._counter.most_common(5)
        return {pid: cnt for pid, cnt in most_common}


class LocationHotspotCalculator(BaseMetricCalculator):
    """
    Determines hotspot locations by rounded lat/lon buckets.
    """

    def __init__(self) -> None:
        self._counter: Counter[str] = Counter()

    @property
    def name(self) -> str:
        return "hotspot_locations"

    def update(self, event: AnalyticsEvent) -> None:
        if event["event_type"] != "location":
            return

        lat = event["payload"].get("lat")
        lon = event["payload"].get("lon")
        if lat is None or lon is None:
            return

        # Bucket into ~10m accuracy
        bucket = f"{round(lat, 2)}_{round(lon, 2)}"
        self._counter[bucket] += 1

    def snapshot(self) -> Dict[str, Any]:
        return dict(self._counter.most_common(3))


class MoodScoreCalculator(BaseMetricCalculator):
    """
    Computes running average mood score (0..1 scale)
    """

    def __init__(self) -> None:
        self._total = 0.0
        self._count = 0

    @property
    def name(self) -> str:
        return "mood_score"

    def update(self, event: AnalyticsEvent) -> None:
        if event["event_type"] != "mood":
            return

        score = event["payload"].get("score")
        if not isinstance(score, (int, float)):
            return

        self._total += float(score)
        self._count += 1

    def snapshot(self) -> Dict[str, Any]:
        avg = self._total / self._count if self._count else 0.0
        return {"average": round(avg, 4), "samples": self._count}


