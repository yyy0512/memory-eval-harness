"""
PrismPocket : module_49.py
================================
Realtime analytics backbone used throughout the application.  The module
implements:

• A lightweight Observer-bus for decoupled metric updates
• A pluggable MetricCalculator framework (Factory pattern)
• A thread-safe, singleton AnalyticsAggregator that hydrates persisted
  state, accepts inbound events from the rest of the app, and publishes
  live metric snapshots.

This component purposely avoids heavy third-party dependencies to remain
portable across the mobile variants shipped via Kivy / BeeWare.
"""
from __future__ import annotations

import json
import logging
import os
import threading
import time
from abc import ABC, abstractmethod
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path
from queue import Queue, Empty
from typing import Any, Dict, List, MutableMapping, Protocol

