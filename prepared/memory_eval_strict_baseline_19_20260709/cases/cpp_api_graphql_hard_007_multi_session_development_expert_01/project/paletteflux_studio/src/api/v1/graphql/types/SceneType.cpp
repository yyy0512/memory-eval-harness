FieldResult<std::string> SceneType::getId(const FieldParams&) const
{
	return _scene->id(); // DomainScene::id() returns std::string (UUID-v4)
}

FieldResult<std::string> SceneType::getName(const FieldParams&) const
{
	return _scene->name();
}

//  -- Layers ----------------------------------------------------------------------------------------------------------
FieldResult<std::vector<LayerObjectPtr>> SceneType::getLayers(
	const FieldParams&                             params,
	std::optional<services::pagination::PageInput> pageInput) const
{
	try
	{
		// Memoise because layers are immutable for the lifetime of a query execution.
		{
			std::scoped_lock lk { _layerCacheMutex };
			if (_layerCache.has_value())
			{
				return *_layerCache;
			}
		}

		// Translate GraphQL pagination input -> domain request object
		services::pagination::PageRequest pageRequest =
			pageInput ? services::pagination::PageRequest { *pageInput }
					  : services::pagination::PageRequest::unpaged();

		auto domainLayers =
			_layerService->fetchLayersForScene(_scene->id(), pageRequest, params.traceId);

		std::vector<LayerObjectPtr> gqlLayers;
		gqlLayers.reserve(domainLayers.size());

		for (const auto& domainLayer : domainLayers)
		{
			gqlLayers.emplace_back(
				std::make_shared<LayerType>(domainLayer, _layerService) // LayerType implements object::Layer
			);
		}

		{
			std::scoped_lock lk { _layerCacheMutex };
			_layerCache = gqlLayers;
		}
		return gqlLayers;
	}
	catch (const std::exception& ex)
	{
		// Convert to GraphQL error
		PLFX_LOG_ERROR("SceneType::getLayers – {}", ex.what());
		throw; // Re-throw ‑ framework converts std::exception to GraphQL `errors{}` array
	}
}

