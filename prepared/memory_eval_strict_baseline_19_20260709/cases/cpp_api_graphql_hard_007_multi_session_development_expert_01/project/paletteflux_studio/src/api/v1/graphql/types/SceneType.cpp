SceneType::SceneType(
	DomainScenePtr                                  scene,
	std::shared_ptr<services::scene::ISceneService> sceneService,
	std::shared_ptr<services::layer::ILayerService> layerService)
	: _scene { std::move(scene) }
	, _sceneService { std::move(sceneService) }
	, _layerService { std::move(layerService) }
{
	if (!_scene)         { throw std::invalid_argument("SceneType: `scene` must not be null"); }
	if (!_sceneService)  { throw std::invalid_argument("SceneType: `sceneService` must not be null"); }
	if (!_layerService)  { throw std::invalid_argument("SceneType: `layerService` must not be null"); }
}

