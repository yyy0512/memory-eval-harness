package com.vitalpulse.cloudcare.common.model;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.databind.annotation.JsonDeserialize;
import com.fasterxml.jackson.databind.annotation.JsonPOJOBuilder;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Past;
import jakarta.validation.constraints.Pattern;

import java.io.Serial;
import java.io.Serializable;
import java.time.LocalDate;
import java.time.Period;
import java.util.Collections;
import java.util.List;
import java.util.Objects;
import java.util.UUID;

/**
 * Immutable representation of a Patient in the VitalPulse ecosystem.
 *
 * <p>The model is intentionally FHIR-inspired but simplified for internal use
 * (full FHIR resources are handled at the integration boundary).<br>
 * This object is small enough to be serialized in Lambda payloads while still
 * carrying the core demographics required by most downstream services.</p>
 *
 * <p>Use {@link Patient.Builder} to construct instances in a type-safe manner.</p>
 */
@JsonInclude(JsonInclude.Include.NON_EMPTY)
@JsonDeserialize(builder = Patient.Builder.class)
public final class Patient implements Serializable {

    @Serial
    private static final long serialVersionUID = -8123874635275848152L;

    // ---------------------------------------------------------------------
    // Core identifiers
    // ---------------------------------------------------------------------

    /**
     * Internal UUID v4 generated by the Command Lambda that creates the patient.
     * Serves as the primary key in DynamoDB and is immutable.
     */
    @NotNull
    private final UUID patientId;

    /**
     * Optional Enterprise Master Patient Identifier (EMPI).
     * Used for multi-facility correlation. Has no uniqueness guarantee inside CloudCare.
     */
    private final String empi;

    // ---------------------------------------------------------------------
    // Demographics
    // ---------------------------------------------------------------------

    @NotNull @NotBlank
    private final String familyName;

    @NotNull @NotBlank
    private final String givenName;

    @Past
    private final LocalDate birthDate;

    @NotNull
    private final Gender gender;

    // ---------------------------------------------------------------------
    // Contacts
    // ---------------------------------------------------------------------

    private final List<ContactPoint> telecom;

    private final Address address;

    // ---------------------------------------------------------------------
    // Constructors & Builder
    // ---------------------------------------------------------------------

    private Patient(Builder b) {
        this.patientId  = b.patientId;
        this.empi       = b.empi;
        this.familyName = b.familyName;
        this.givenName  = b.givenName;
        this.birthDate  = b.birthDate;
        this.gender     = b.gender;
        this.telecom    = b.telecom == null ? Collections.emptyList() : List.copyOf(b.telecom);
        this.address    = b.address;
    }

    @JsonCreator
    public static Patient create( // for Jackson deserialization without explicitly using Builder
            @JsonProperty("patientId") UUID patientId,
            @JsonProperty("empi")      String empi,
            @JsonProperty("familyName") String familyName,
            @JsonProperty("givenName")  String givenName,
            @JsonProperty("birthDate")  LocalDate birthDate,
            @JsonProperty("gender")     Gender gender,
            @JsonProperty("telecom")    List<ContactPoint> telecom,
            @JsonProperty("address")    Address address) {
        return new Builder()
                .patientId(patientId)
                .empi(empi)
                .familyName(familyName)
                .givenName(givenName)
                .birthDate(birthDate)
                .gender(gender)
                .telecom(telecom)
                .address(address)
                .build();
    }

    // ---------------------------------------------------------------------
    // Domain helpers
    // ---------------------------------------------------------------------

    /**
     * Returns the patient's age in complete years.
     */
    @JsonIgnore
    public int getAge() {
        return birthDate == null ? 0 : Period.between(birthDate, LocalDate.now()).getYears();
    }

    /**
     * Convenience determination of whether the patient is a minor in the United States (&lt; 18 years).
     */
    @JsonIgnore
    public boolean isMinor() {
        return getAge() < 18;
    }

    // ---------------------------------------------------------------------
    // Getters
    // ---------------------------------------------------------------------

    public UUID getPatientId() {
        return patientId;
    }

    public String getEmpi() {
        return empi;
    }

    public String getFamilyName() {
        return familyName;
    }

    public String getGivenName() {
        return givenName;
    }

    public LocalDate getBirthDate() {
        return birthDate;
    }

    public Gender getGender() {
        return gender;
    }

    public List<ContactPoint> getTelecom() {
        return telecom;
    }

    public Address getAddress() {
        return address;
    }

    // ---------------------------------------------------------------------
    // Builder
    // ---------------------------------------------------------------------

    @JsonPOJOBuilder(withPrefix = "")
    public static class Builder {
        private UUID patientId;
        private String empi;
        private String familyName;
        private String givenName;
        private LocalDate birthDate;
        private Gender gender;
        private List<ContactPoint> telecom;
        private Address address;

        public Builder patientId(UUID patientId) {
            this.patientId = patientId;
            return this;
        }

        public Builder empi(String empi) {
            this.empi = empi;
            return this;
        }

        public Builder familyName(String familyName) {
            this.familyName = familyName;
            return this;
        }

        public Builder givenName(String givenName) {
            this.givenName = givenName;
            return this;
        }

        public Builder birthDate(LocalDate birthDate) {
            this.birthDate = birthDate;
            return this;
        }

        public Builder gender(Gender gender) {
            this.gender = gender;
            return this;
        }

        public Builder telecom(List<ContactPoint> telecom) {
            this.telecom = telecom;
            return this;
        }

        public Builder address(Address address) {
            this.address = address;
            return this;
        }

        public Patient build() {
            // basic validation
            Objects.requireNonNull(patientId,  "patientId");
            Objects.requireNonNull(familyName, "familyName");
            Objects.requireNonNull(givenName,  "givenName");
            Objects.requireNonNull(gender,     "gender");
            return new Patient(this);
        }
    }

    // ---------------------------------------------------------------------
    // Equality
    // ---------------------------------------------------------------------

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Patient patient)) return false;
        return Objects.equals(patientId, patient.patientId);
    }

    @Override
    public int hashCode() {
        return Objects.hash(patientId);
    }

    @Override
    public String toString() {
        return "Patient{" +
                "patientId=" + patientId +
                ", empi='" + empi + '\'' +
                ", familyName='" + familyName + '\'' +
                ", givenName='" + givenName + '\'' +
                ", birthDate=" + birthDate +
                ", gender=" + gender +
                '}';
    }

    // ---------------------------------------------------------------------
    // Nested Types
    // ---------------------------------------------------------------------

    /**
     * Administrative gender as enumerated in FHIR R4.
     */
    public enum Gender {
        male,
        female,
        other,
        unknown
    }

    /**
     * Represents a telecom entry (phone, email, etc.)
     */
    @JsonInclude(JsonInclude.Include.NON_EMPTY)
    public static final class ContactPoint implements Serializable {
        @Serial
        private static final long serialVersionUID = 4970014040490572769L;

        public enum System { phone, email, sms }

        @NotNull
        private final System system;

        @NotBlank
        private final String value;

        private final String use; // home | work | temp | old | mobile

        @JsonCreator
        public ContactPoint(@JsonProperty("system") System system,
                            @JsonProperty("value") String value,
                            @JsonProperty("use") String use) {
            this.system = system;
            this.value  = value;
            this.use    = use;
        }

        public System getSystem() {
            return system;
        }

        public String getValue() {
            return value;
        }

        public String getUse() {
            return use;
        }

        @Override
        public boolean equals(Object o) {
            if (this == o) return true;
            if (!(o instanceof ContactPoint that)) return false;
            return system == that.system && Objects.equals(value, that.value);
        }

        @Override
        public int hashCode() {
            return Objects.hash(system, value);
        }

        @Override
        public String toString() {
            return "ContactPoint{" + system + '=' + value + '}';
        }
    }

    /**
     * Simplified postal address model.
     */
    @JsonInclude(JsonInclude.Include.NON_EMPTY)
    public static final class Address implements Serializable {
        @Serial
        private static final long serialVersionUID = 6792416214962752753L;

        private final String line1;
        private final String line2;
        private final String city;
        private final String state;
        @Pattern(regexp = "\\d{5}(-\\d{4})?")
        private final String postalCode;
        private final String country;

        @JsonCreator
        public Address(@JsonProperty("line1") String line1,
                       @JsonProperty("line2") String line2,
                       @JsonProperty("city") String city,
                       @JsonProperty("state") String state,
                       @JsonProperty("postalCode") String postalCode,
                       @JsonProperty("country") String country) {
            this.line1      = line1;
            this.line2      = line2;
            this.city       = city;
            this.state      = state;
            this.postalCode = postalCode;
            this.country    = country;
        }

        public String getLine1() {
            return line1;
        }

        public String getLine2() {
            return line2;
        }

        public String getCity() {
            return city;
        }

        public String getState() {
            return state;
        }

        public String getPostalCode() {
            return postalCode;
        }

        public String getCountry() {
            return country;
        }

        @Override
        public String toString() {
            return "Address{" + line1 +
                    (line2 != null ? ", " + line2 : "") +
                    ", " + city + ", " + state + ' ' + postalCode +
                    ", " + country + '}';
        }

        @Override
        public boolean equals(Object o) {
            if (this == o) return true;
            if (!(o instanceof Address address)) return false;
            return Objects.equals(line1, address.line1) &&
                   Objects.equals(city, address.city) &&
                   Objects.equals(state, address.state) &&
                   Objects.equals(postalCode, address.postalCode);
        }

        @Override
        public int hashCode() {
            return Objects.hash(line1, city, state, postalCode);
        }
    }
}